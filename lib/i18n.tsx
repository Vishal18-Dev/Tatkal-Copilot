const dicts: Record<Lang, Dict> = { en, hi };

interface Ctx {
  lang: Lang;
  setLang: (l: Lang) => void;
  toggle: () => void;
  t: (key: string) => string;
}

const LanguageContext = createContext<Ctx | null>(null);

const LANG_KEY = "tatkal.lang.v1";

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>("en");

  // Restore the saved language on mount (client-only, avoids SSR mismatch).
  useEffect(() => {
    try {
      const saved = localStorage.getItem(LANG_KEY);
      if (saved === "hi" || saved === "en") setLangState(saved);
    } catch {
      /* ignore */
    }
  }, []);

  const persist = (l: Lang) => {
    try {
      localStorage.setItem(LANG_KEY, l);
    } catch {
      /* ignore */
    }
  };

  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    persist(l);
  }, []);

  const toggle = useCallback(
    () =>
      setLangState((prev) => {
        const next = prev === "en" ? "hi" : "en";
        persist(next);
        return next;
      }),
    []
  );

  const t = useCallback(
    (key: string) => {
      const v = dicts[lang][key] ?? dicts.en[key] ?? key;
      return Array.isArray(v) ? v.join(" ") : v;
    },
    [lang]
  );

  const value = useMemo(() => ({ lang, setLang, toggle, t }), [lang, toggle, t]);

  return (
    <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>
  );
}

export function useLang(): Ctx {
  const ctx = useContext(LanguageContext);
  if (!ctx) throw new Error("useLang must be used within LanguageProvider");
  return ctx;
}
